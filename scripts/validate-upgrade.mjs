import fs from 'node:fs';
import assert from 'node:assert/strict';
import {benchmark,boostTransient,recovery} from '../dist/evidence.js';
const ref=JSON.parse(fs.readFileSync(new URL('../dist/data/reference.json',import.meta.url)));
let count=0,result=benchmark(ref,(n,total)=>{count=n;assert.equal(total,100)});
assert.equal(count,100);assert.equal(result.records.length,30);
for(const row of result.records)assert(row.samples.every(s=>s.audit.finite&&s.audit.bounded&&s.audit.maxBalance<1e-5));
const full=result.records.find(r=>r.case==='clean'&&r.type===4);
assert.equal(full.activity,.104);assert(Math.abs(full.ss-99.7096577)<.0001);
const noisy=result.records.find(r=>r.case==='noise'&&r.type===4);
assert.equal(noisy.seeds,8);assert(noisy.sd>0);
assert.equal(recovery(Array.from({length:6},()=>({P:99,pmpp:100}))),0);
assert.equal(recovery(Array.from({length:6},()=>({P:98,pmpp:100}))),null);
const a=boostTransient(),b=boostTransient({dt:1e-6});let error=0;
for(let k=0;k<a.rows.length;k++)error=Math.max(error,Math.abs(a.rows[k].V-b.rows[k].V),Math.abs(a.rows[k].I-b.rows[k].I));
assert(error<1e-6);assert(a.energyResidual<1e-9);assert(Math.abs(a.rows.at(-1).V-a.target)<.001);assert(a.ccm);
assert(!boostTransient({D0:.7,D1:.1}).ccm);
assert.throws(()=>boostTransient({D1:1}));
console.log('PASS: 100 matched runs, summaries and audits; acquisition metric; RK4 convergence, equilibrium, energy identity and CCM invalidity detection.');
